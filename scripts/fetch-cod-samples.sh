#!/usr/bin/env bash
# Download curated COD CIFs into public/samples/cod/ for same-origin GH Pages loads.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/public/samples/cod"
mkdir -p "$DIR"
IDS=(
1000001 1000032 1000042 1000061 1010916 1010920 1010954 1010962 1010995 1100025 1100303 1507756 1507774 1508519 1512506 1517671 1528996 1532834 1537333 1544740 2000064 2001013 2002258 2100301 2100616 2101320 2101852 2101983 2101989 2104741 2212817 4114818 7206076 9000000 9000001 9007681 9007689 9008462 9008465 9008483 9008564 9008565 9008568 9011577 9012596 1010925 1010940 1010953 1507776 1521116 1532503 2002887 4124843 9000046 9008566
)
for id in "${IDS[@]}"; do
  echo "COD $id…"
  curl -fsSL "https://www.crystallography.net/cod/${id}.cif" -o "$DIR/${id}.cif"
done
python3 "$ROOT/scripts/build-cod-manifest.py"
echo "Done."
