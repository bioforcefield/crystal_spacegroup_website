/** Pure helpers for the CIF viewport UX (review fixes, Oct 2026). */
import { cellCount, fitsCap, type CellMultiples } from '../supercell'
import type { ResolvedAtom } from './measureModel'
import type { ExpandedStructure } from './types'

/** Option state for one supercell axis value given the other two axes (strict cap). */
export function axisOptionState(
  m: CellMultiples,
  axis: 0 | 1 | 2,
  n: number,
  perCell: number,
  cap: number,
): { disabled: boolean; reason: string | null } {
  const next: CellMultiples = [m[0], m[1], m[2]]
  next[axis] = n
  if (fitsCap(next, perCell, cap)) return { disabled: false, reason: null }
  const total = perCell * cellCount(next)
  return {
    disabled: true,
    reason: `${next.join('×')} = ${total.toLocaleString('en-US')} atoms > ${cap.toLocaleString('en-US')} cap`,
  }
}

/** Above 2×2×2 the view gets dense: fade interior edges and shrink replica atoms. */
export function isDenseSupercell(m: CellMultiples): boolean {
  return cellCount(m) > 8
}

/** Download filename: base + optional sg number + suffix. */
export function cifDownloadName(base: string, sg: number | null | undefined, suffix: string, ext: string): string {
  const sgTag = sg != null ? `_sg${sg}` : ''
  return `${base}${sgTag}${suffix ? `_${suffix}` : ''}.${ext}`
}

/** Number of distinct molecules (fragments) generated by op 1 (the asymmetric unit). */
export function asuFragmentCount(s: Pick<ExpandedStructure, 'atoms'>): number {
  const ids = new Set<number>()
  for (const a of s.atoms) if (a.opIndex === 1) ids.add(a.moleculeId)
  return ids.size
}

/** Z′ wording that reconciles Z′ with multi-fragment asymmetric units. */
export function zPrimeLabel(zPrime: number | string, fragments: number): string {
  return fragments > 1
    ? `Z′ = ${zPrime} (asymmetric unit contains ${fragments} fragments)`
    : `Z′ = ${zPrime}`
}

/** Per-op molecule-count wording tied to the Z′ note. */
export function molPerOpLabel(mols: number, fragments: number): string {
  return fragments > 1 && mols === fragments ? `${mols} fragments (1 ASU)` : `${mols} mol`
}

/** For each consecutive pick pair, true when the two atoms are NOT covalently bonded. */
export function nonBondedSteps(
  s: Pick<ExpandedStructure, 'bonds'>,
  atoms: Pick<ResolvedAtom, 'pick' | 'moleculeKey'>[],
): boolean[] {
  const key = (a: number, b: number) => (a < b ? `${a}-${b}` : `${b}-${a}`)
  const set = new Set(s.bonds.map((b) => key(b.a, b.b)))
  const out: boolean[] = []
  for (let i = 1; i < atoms.length; i++) {
    const p = atoms[i - 1]!
    const q = atoms[i]!
    out.push(!(p.moleculeKey === q.moleculeKey && set.has(key(p.pick.ai, q.pick.ai))))
  }
  return out
}

/** Labels for the molecule-pair result: which pick is A and which is B. */
export function pairPickLabels(
  atoms: Pick<ResolvedAtom, 'moleculeKey' | 'label' | 'triplet'>[],
  opIndexOf: (i: number) => number,
): { a: string; b: string } | null {
  const ia = 0
  const ib = atoms.findIndex((x) => x.moleculeKey !== atoms[0]?.moleculeKey)
  if (!atoms.length || ib < 0) return null
  return {
    a: `A = pick ${ia + 1} (${atoms[ia]!.label}, op ${opIndexOf(ia)})`,
    b: `B = pick ${ib + 1} (${atoms[ib]!.label}, op ${opIndexOf(ib)})`,
  }
}

/** Roving tabindex: next index for arrow keys, or null if key not handled. */
export function rovingNext(i: number, key: string, n: number): number | null {
  if (n <= 0) return null
  if (key === 'ArrowRight' || key === 'ArrowDown') return (i + 1) % n
  if (key === 'ArrowLeft' || key === 'ArrowUp') return (i - 1 + n) % n
  if (key === 'Home') return 0
  if (key === 'End') return n - 1
  return null
}

/** Esc priority: close the innermost UI first. Returns which thing Esc should act on. */
export function escTarget(state: {
  menuOpen: boolean
  measureOn: boolean
  hasPicks: boolean
  panelOpen: boolean
}): 'menu' | 'measure' | 'panel' | null {
  if (state.menuOpen) return 'menu'
  if (state.measureOn) return 'measure'
  if (state.panelOpen) return 'panel'
  return null
}
